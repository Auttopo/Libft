#include "libft.h"

char	*ft_strdup(const char *src)
{
	char	*copy;
	size_t	i;

	copy = NULL;
	i = 0;
	copy = malloc(sizeof(char) * (ft_strlen(src) + 1));
	if (copy == NULL)
		return (NULL);
	while (src[i] != '\0')
	{
		copy[i] = src[i];
		i++;
	}
	copy[i] = '\0';
	return (copy);
}

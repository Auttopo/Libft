#include "libft.h"

size_t	ft_strlcpy(char *dst, const char *src, size_t size)
{
	size_t	i;
	size_t	lenth;

	i = 0;
	lenth = 0;
	while (src[lenth])
		lenth++;
	if (size < 1)
		return (lenth);
	while (src[i] && i < (size - 1))
	{
		dst[i] = src[i];
		i++;
	}
	dst[i] = '\0';
	return (lenth);
}
